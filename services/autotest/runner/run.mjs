#!/usr/bin/env node
/**
 * Autotest e2e runner — the Node half of the UI channel.
 *
 *   node run.mjs --spec <spec.json>
 *
 * Reads one spec, prepares a throwaway e2e project next to the e2e install (so
 * `e2e` and `@e2e-dev/web` resolve), runs the case and forwards the runner's
 * own events as RunEvent lines on stdout.
 *
 * Ownership: this process only reports steps and artifacts. The Python
 * dispatcher owns `run.start` / `run.end`, the `executions` row and the final
 * verdict from this process's exit code, so a step can never invent a pass.
 *
 * Environment:
 *   AUTOTEST_E2E_HOME   directory holding node_modules/e2e (required)
 *   AUTOTEST_E2E_KEEP   set to 1 to keep the prepared project for debugging
 */
import { spawn } from "node:child_process";
import { cp, mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import { createInterface } from "node:readline";

const EVENT_PREFIX = "@@E2E@@";

function fail(message) {
  process.stderr.write(`[autotest-runner] ${message}\n`);
  process.exit(2);
}

function argValue(flag) {
  const index = process.argv.indexOf(flag);
  return index >= 0 ? process.argv[index + 1] : undefined;
}

const specPath = argValue("--spec");
if (!specPath) fail("missing --spec <spec.json>");
const spec = JSON.parse(await readFile(specPath, "utf8"));

const e2eHome = resolve(process.env.AUTOTEST_E2E_HOME ?? "");
if (!e2eHome || !existsSync(join(e2eHome, "node_modules", "e2e", "package.json"))) {
  fail(`AUTOTEST_E2E_HOME must point at a directory with node_modules/e2e (got ${e2eHome || "empty"})`);
}

const caseFile = resolve(spec.scriptPath ?? "");
if (!existsSync(caseFile)) fail(`case file not found: ${caseFile}`);

const runRoot = join(e2eHome, ".autotest-runs");
await mkdir(runRoot, { recursive: true });
const workDir = await mkdtemp(join(runRoot, "run-"));
const testsDir = join(workDir, "tests");
await mkdir(testsDir, { recursive: true });
await cp(caseFile, join(testsDir, basename(caseFile)));

const targetUrl = spec.target?.url ?? "http://127.0.0.1:3000";
const config = `// generated by the Autotest e2e runner — do not edit
import type { E2EConfig } from "e2e";
import { web } from "@e2e-dev/web";

export default {
  targets: [{ engine: web(), app: { url: ${JSON.stringify(targetUrl)} } }],
  reporters: [
    {
      name: "autotest-ndjson",
      onEvent(event: unknown) {
        process.stdout.write(${JSON.stringify(EVENT_PREFIX)} + JSON.stringify(event) + "\\n");
      },
    },
  ],
} satisfies E2EConfig;
`;
await writeFile(join(workDir, "e2e.config.ts"), config, "utf8");

const cli = join(e2eHome, "node_modules", "e2e", "dist", "cli", "bin.js");
const child = spawn(process.execPath, [cli, "run", "--reporter", "list"], {
  cwd: workDir,
  env: {
    ...process.env,
    E2E_TELEMETRY_DISABLED: "1",
    AUTOTEST_TARGET_URL: targetUrl,
  },
  stdio: ["ignore", "pipe", "pipe"],
  windowsHide: true,
});

let emitted = 0;
let stepCounter = 0;
const openSteps = [];
const stats = { started: 0, steps: 0, finished: 0, artifacts: 0 };

/** Map one e2e event to zero or more RunEvent lines. */
function translate(event) {
  if (!event || typeof event !== "object") return;
  if (event.type === "test-started") {
    stats.started += 1;
    return;
  }
  if (event.type === "step") {
    const progress = event.progress ?? {};
    const phase = String(progress.state ?? progress.phase ?? "");
    const knownId = progress.id ?? progress.stepId;
    const isStart = /start/i.test(phase) || !phase;
    const isEnd = /finish|end|complete/i.test(phase);
    const label = String(
      progress.title ?? progress.label ?? progress.name ?? progress.kind ?? "step",
    );
    const kind = /assert|expect|check/i.test(String(progress.kind ?? label)) ? "assert" : "act";

    if (isStart) {
      const stepId = String(knownId ?? `step-${stepCounter++}`);
      openSteps.push(stepId);
      stats.steps += 1;
      emit({ type: "step.start", caseId: spec.caseId, stepId, index: stats.steps, kind, label });
      return;
    }
    if (isEnd) {
      // Pair with the newest open step when the runner omits an id.
      const stepId = String(knownId ?? openSteps.pop() ?? `step-${stepCounter++}`);
      emit({
        type: "step.end",
        caseId: spec.caseId,
        stepId,
        status: mapStatus(progress.status),
        durationMs: Number(progress.durationMs ?? 0),
        replayHit: Boolean(progress.replayHit ?? progress.cached),
        detail: progress.error ? { error: String(progress.error) } : undefined,
      });
    }
    return;
  }
  if (event.type === "test-finished") {
    stats.finished += 1;
    const result = event.result ?? {};
    for (const attempt of result.attempts ?? []) {
      for (const artifact of attempt.artifacts ?? []) {
        stats.artifacts += 1;
        emit({
          type: "artifact",
          caseId: spec.caseId,
          kind: String(artifact.kind ?? "log"),
          path: String(artifact.path ?? artifact.file ?? ""),
          bytes: Number.isFinite(artifact.size) ? Number(artifact.size) : undefined,
        });
      }
    }
    return;
  }
  if (event.type === "run-error") {
    const error = event.error ?? {};
    process.stderr.write(`[autotest-runner] run error: ${error.code ?? ""} ${error.message ?? ""}\n`);
  }
}

function mapStatus(status) {
  const value = String(status ?? "").toLowerCase();
  if (value.startsWith("pass") || value === "ok" || value === "success") return "pass";
  if (value.startsWith("skip")) return "skip";
  return "fail";
}

function emit(event) {
  if (event.detail === undefined) delete event.detail;
  if (event.bytes === undefined) delete event.bytes;
  emitted += 1;
  process.stdout.write(JSON.stringify(event) + "\n");
}

const stdout = createInterface({ input: child.stdout });
stdout.on("line", (line) => {
  if (!line.startsWith(EVENT_PREFIX)) {
    // Human-facing progress from the e2e list reporter.
    process.stderr.write(line + "\n");
    return;
  }
  try {
    const parsed = JSON.parse(line.slice(EVENT_PREFIX.length));
    if (process.env.AUTOTEST_E2E_DEBUG === "1") {
      process.stderr.write(`[autotest-runner][raw] ${JSON.stringify(parsed).slice(0, 4000)}\n`);
    }
    translate(parsed);
  } catch (error) {
    process.stderr.write(`[autotest-runner] unparsable event: ${error}\n`);
  }
});

const stderr = createInterface({ input: child.stderr });
stderr.on("line", (line) => process.stderr.write(line + "\n"));

const timeoutMs = Number(spec.timeoutMs ?? 300_000);
const killer = setTimeout(() => {
  process.stderr.write(`[autotest-runner] timeout after ${timeoutMs} ms, killing the run\n`);
  child.kill("SIGKILL");
}, timeoutMs);

const exitCode = await new Promise((resolveExit) => {
  child.on("error", (error) => {
    process.stderr.write(`[autotest-runner] failed to start e2e: ${error}\n`);
    resolveExit(2);
  });
  child.on("exit", (code, signal) => {
    if (signal) process.stderr.write(`[autotest-runner] e2e exited on ${signal}\n`);
    resolveExit(code ?? 2);
  });
});
clearTimeout(killer);
stdout.close();
stderr.close();

// The reporter does not see test-finished for every failure path, so the
// authoritative record comes from the report the CLI always writes. Keep the
// artifacts (they hold the failure screenshot) next to the case instead of
// letting them die with the throwaway project.
const reportPath = join(workDir, ".e2e", "report.json");
let artifactsKept = 0;
let firstFailure = "";
try {
  const report = JSON.parse(await readFile(reportPath, "utf8"));
  const results = report?.run?.results ?? [];
  const keepRoot = join(resolve(spec.artifactsDir ?? workDir), "artifacts", spec.runId ?? "run");
  for (const result of results) {
    for (const attempt of result.attempts ?? []) {
      if (!firstFailure && attempt.error) {
        const code = attempt.error.code ?? "";
        const message = String(attempt.error.message ?? "").split("\n")[0];
        firstFailure = `${code} ${message}`.trim();
      }
      for (const artifact of attempt.artifacts ?? []) {
        const source = join(workDir, ".e2e", "results", String(artifact.path ?? ""));
        const target = join(keepRoot, String(artifact.path ?? ""));
        try {
          await mkdir(dirname(target), { recursive: true });
          await cp(source, target);
          artifactsKept += 1;
          emit({
            type: "artifact",
            caseId: spec.caseId,
            kind: String(artifact.kind ?? "log"),
            path: target,
            bytes: Number.isFinite(artifact.size) ? Number(artifact.size) : undefined,
          });
        } catch (error) {
          process.stderr.write(`[autotest-runner] artifact not copied: ${artifact.path} (${error})\n`);
        }
      }
    }
  }
} catch (error) {
  process.stderr.write(`[autotest-runner] report unreadable: ${error}\n`);
}

process.stderr.write(
  `[autotest-runner] e2e exit=${exitCode} started=${stats.started} steps=${stats.steps} ` +
    `artifacts=${artifactsKept} emitted=${emitted}\n`,
);

if (firstFailure) {
  // Last line on purpose: the Python side reports the last stderr line as the
  // failure reason.
  process.stderr.write(`[autotest-runner] failure: ${firstFailure}\n`);
}

if (process.env.AUTOTEST_E2E_KEEP !== "1") {
  await rm(workDir, { recursive: true, force: true }).catch(() => {});
}
process.exit(exitCode);
